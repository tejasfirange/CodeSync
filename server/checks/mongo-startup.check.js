import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mongoose from 'mongoose';

// Explicit local port only. Never load application .env or target its database.
const portArgument = process.argv[2];
const port = Number(portArgument);
if (!/^\d+$/.test(portArgument || '') || port < 1 || port > 65535) {
  throw new Error('Usage: npm run test:mongodb --workspace server -- <isolated-local-mongodb-port>');
}

const databaseName = `codesync_startup_test_${randomUUID().replaceAll('-', '')}`;
mongoose.set('autoCreate', false);
mongoose.set('autoIndex', false);
const { default: CodeFile, ensureCodeFileIndexes } = await import('../src/models/CodeFile.model.js');

try {
  await mongoose.connect(`mongodb://127.0.0.1:${port}`, {
    dbName: databaseName,
    serverSelectionTimeoutMS: 10000
  });

  // Reproduce the exact operation that previously aborted startServer().
  await assert.rejects(CodeFile.collection.indexes(), (error) => error.code === 26);
  console.log('Reproduced NamespaceNotFound on a fresh collection.');

  await ensureCodeFileIndexes();
  const indexes = await CodeFile.collection.indexes();
  const pathIndex = indexes.find((index) => index.key.project === 1 && index.key.path === 1);
  assert.ok(pathIndex?.unique && pathIndex?.sparse);
  assert.ok(indexes.some((index) => index.key.room === 1 && index.key.updatedAt === -1));
  console.log('Fresh-database index initialization passed.');

  const legacy = {
    project: new mongoose.Types.ObjectId(),
    room: new mongoose.Types.ObjectId(),
    filename: 'legacy.js',
    content: 'console.log("synthetic fixture");'
  };
  const { insertedId } = await CodeFile.collection.insertOne(legacy);
  await ensureCodeFileIndexes();
  await ensureCodeFileIndexes();
  const saved = await CodeFile.collection.findOne({ _id: insertedId });
  assert.equal(saved.path, 'legacy.js');
  assert.equal(saved.content, legacy.content);
  assert.equal(await CodeFile.countDocuments(), 1);
  console.log('Repeated initialization and legacy backfill preserve test data.');
} finally {
  try {
    // Only the unique database generated by this invocation may be removed.
    if (mongoose.connection.readyState === 1 && mongoose.connection.name === databaseName) {
      await mongoose.connection.db.dropDatabase();
    }
  } finally {
    await mongoose.disconnect();
  }
}
